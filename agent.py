import json
import os
import re
import urllib.request
from datetime import datetime, timezone

LEETCODE_GRAPHQL = "https://leetcode.com/graphql"
GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")


def post_json(url, payload, headers=None):
    data = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url, data=data, headers={"Content-Type": "application/json", **(headers or {})}
    )
    with urllib.request.urlopen(request, timeout=45) as response:
        return json.loads(response.read().decode("utf-8"))


def get_daily_problem():
    query = """
    query questionOfToday {
      activeDailyCodingChallengeQuestion {
        date
        link
        question {
          title
          titleSlug
          difficulty
          content
          topicTags { name }
          codeSnippets { lang langSlug code }
        }
      }
    }
    """
    result = post_json(LEETCODE_GRAPHQL, {"query": query})
    item = result.get("data", {}).get("activeDailyCodingChallengeQuestion")
    if not item or not item.get("question"):
        raise RuntimeError("Could not retrieve today's challenge from LeetCode.")
    q = item["question"]
    java_template = next(
        (snippet.get("code", "") for snippet in q.get("codeSnippets", [])
         if snippet.get("langSlug") == "java"),
        ""
    )
    return {
        "date": item.get("date", ""),
        "url": "https://leetcode.com" + item.get("link", ""),
        "title": q.get("title", ""),
        "slug": q.get("titleSlug", ""),
        "difficulty": q.get("difficulty", ""),
        "statement_html": q.get("content", ""),
        "topics": [tag["name"] for tag in q.get("topicTags", [])],
        "java_template": java_template,
    }


def solve_with_gemini(problem):
    api_key = os.environ["GEMINI_API_KEY"]
    endpoint = (
        f"https://generativelanguage.googleapis.com/v1beta/models/"
        f"{GEMINI_MODEL}:generateContent?key={api_key}"
    )
    prompt = f"""
You are helping a learner practice LeetCode. Produce a correct Java solution
for the following Daily Challenge. Return Markdown with:
1. Brief approach
2. Time and space complexity
3. One complete LeetCode Java submission using the expected class/method
signature from the provided Java template, if available.
Do not claim it is accepted unless LeetCode confirms it.

Title: {problem['title']}
Difficulty: {problem['difficulty']}
URL: {problem['url']}
Topics: {', '.join(problem['topics'])}
Java starter template:
{problem['java_template'] or '(not provided)'}

Problem statement (HTML):
{problem['statement_html']}
"""
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"temperature": 0.2}
    }
    result = post_json(endpoint, payload)
    candidates = result.get("candidates", [])
    if not candidates:
        raise RuntimeError("Gemini returned no answer: " + json.dumps(result)[:1200])
    parts = candidates[0].get("content", {}).get("parts", [])
    answer = "\n".join(part.get("text", "") for part in parts).strip()
    if not answer:
        raise RuntimeError("Gemini response was empty.")
    return answer


def main():
    problem = get_daily_problem()
    answer = solve_with_gemini(problem)
    os.makedirs("output", exist_ok=True)
    date = problem.get("date") or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    safe_slug = re.sub(r"[^a-zA-Z0-9_-]", "-", problem.get("slug") or "daily-challenge")
    path = f"output/{date}-{safe_slug}.md"
    with open(path, "w", encoding="utf-8") as file:
        file.write(f"# {problem['title']}\n\n")
        file.write(f"- **Date:** {date}\n- **Difficulty:** {problem['difficulty']}\n")
        file.write(f"- **Problem:** {problem['url']}\n\n")
        file.write("> Generated by AI. Review and test the solution yourself; it has not been submitted to LeetCode.\n\n")
        file.write(answer + "\n")
    print(f"Generated solution: {path}")
    print(f"Problem: {problem['title']} ({problem['difficulty']})")
    print(f"Review at: {problem['url']}")


if __name__ == "__main__":
    main()
